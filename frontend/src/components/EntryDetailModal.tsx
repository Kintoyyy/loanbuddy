import { useEffect, useState } from "react";
import { AlertTriangle, FileText, Lock, Paperclip, Plus, Printer, X } from "lucide-react";
import {
  addEntryPenalty,
  type Entry,
  type EntryCollection,
  type EntryPenalty,
  type PenaltyRequest,
  getCollectionProof,
  getEntryCollections,
  getEntryProof,
} from "../api";
import { getAgreementSettings } from "../settingsStore";
import ProofViewerModal from "./ProofViewerModal";

interface Props {
  entry: Entry;
  lenderName: string;
  onClose: () => void;
  onPenaltyAdded?: (penalty: EntryPenalty) => void;
}

function fmtDate(d: string | null | undefined) {
  if (!d) return "—";
  const s = d.split("T")[0];
  const [y, m, day] = s.split("-");
  return new Date(Number(y), Number(m) - 1, Number(day)).toLocaleDateString("en-US", {
    month: "long", day: "numeric", year: "numeric",
  });
}

function fmtAmt(n: number) {
  return n.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function buildPrintHtml(opts: {
  lenderName: string;
  entry: Entry;
  todayStr: string;
  sigHtml: string;
  additionalTerms: string;
}) {
  const { lenderName, entry, todayStr, sigHtml, additionalTerms } = opts;
  const extraTerms = additionalTerms.trim();
  const desc = entry.notes?.trim();
  const dueDate = entry.expected_payback_date;
  const amount = Number(entry.original_amount);
  const currency = entry.currency;
  let sec = 1;
  const s = () => `SECTION ${sec++}`;
  return `<!DOCTYPE html><html><head>
<title>Loan Agreement — ${entry.debtor_name}</title>
<style>
  body{font-family:"Times New Roman",serif;max-width:720px;margin:40px auto;line-height:1.8;color:#111;font-size:14px}
  h1{text-align:center;font-size:20px;text-transform:uppercase;letter-spacing:3px;margin:0 0 6px}
  .subtitle{text-align:center;font-size:11px;color:#555;margin-bottom:4px}
  h2{font-size:13px;font-weight:bold;text-transform:uppercase;letter-spacing:1px;margin:22px 0 6px}
  hr{border:none;border-top:2px solid #111;margin:18px 0}
  .hr-thin{border:none;border-top:1px solid #aaa;margin:14px 0}
  .parties{display:grid;grid-template-columns:1fr 1fr;gap:40px;margin:18px 0}
  .party-label{font-size:11px;font-weight:bold;text-transform:uppercase;letter-spacing:1px;margin-bottom:4px;color:#444}
  .sig-grid{display:grid;grid-template-columns:1fr 1fr;gap:40px;margin-top:28px}
  .sig-label{font-size:11px;font-weight:bold;text-transform:uppercase;letter-spacing:1px;margin-bottom:8px}
  .sig-line{border-bottom:1px solid #333;width:280px;height:72px;display:block}
  .sig-meta{font-size:11px;color:#555;margin-top:4px}
  .footer{text-align:center;font-size:11px;color:#999;margin-top:40px}
  p{margin:0 0 8px}ul{margin:4px 0 8px;padding-left:20px}li{margin-bottom:2px}
</style>
</head><body>
<h1>Personal Loan Agreement</h1>
<p class="subtitle">A Legally Binding Agreement</p>
<hr/>
<p>This Personal Loan Agreement ("Agreement") is entered into as of <strong>${fmtDate(entry.lending_date)}</strong>, by and between:</p>
<div class="parties">
  <div><div class="party-label">Lender</div><p><strong>${lenderName}</strong></p></div>
  <div><div class="party-label">Borrower</div><p><strong>${entry.debtor_name}</strong></p></div>
</div>
<hr/>
<h2>${s()} — Loan Amount</h2>
<p>The Lender agrees to loan the Borrower the principal sum of <strong>${currency} ${fmtAmt(amount)}</strong>. The Borrower acknowledges receipt of this amount on <strong>${fmtDate(entry.lending_date)}</strong>.</p>
<h2>${s()} — Repayment</h2>
<p>${dueDate ? `The Borrower agrees to repay the full principal amount of <strong>${currency} ${fmtAmt(amount)}</strong> on or before <strong>${fmtDate(dueDate)}</strong>.` : `The Borrower agrees to repay the full principal amount of <strong>${currency} ${fmtAmt(amount)}</strong> upon demand by the Lender.`}</p>
${desc ? `<h2>${s()} — Purpose of Loan</h2><p>${desc}</p>` : ""}
<h2>${s()} — Interest</h2>
<p>This loan is granted interest-free unless both parties agree otherwise in a separate written amendment.</p>
<h2>${s()} — Default</h2>
<p>Should the Borrower fail to repay by the agreed date, the Lender reserves the right to pursue all available legal remedies.</p>
${extraTerms ? `<h2>${s()} — Additional Terms</h2><p>${extraTerms.replace(/\n/g, "<br/>")}</p>` : ""}
<h2>${s()} — Acknowledgment &amp; Signatures</h2>
<p>By signing below, each party confirms they have read, understood, and agreed to the terms of this Agreement.</p>
<div class="hr-thin"></div>
<div class="sig-grid">
  <div><div class="sig-label">Lender's Signature</div><span class="sig-line"></span><div class="sig-meta">Name: ${lenderName}<br/>Date: ${todayStr}</div></div>
  <div><div class="sig-label">Borrower's Signature</div>${sigHtml}<div class="sig-meta">Name: ${entry.debtor_name}<br/>Date: ${fmtDate(entry.lending_date)}</div></div>
</div>
<hr/>
<p class="footer">Generated by LoanBuddy &middot; ${todayStr}</p>
</body></html>`;
}

const STATUS_COLORS: Record<string, string> = {
  Open: "bg-slate-100 text-slate-600",
  "Partially Collected": "bg-amber-100 text-amber-700",
  Closed: "bg-emerald-100 text-emerald-700",
};

const TODAY = new Date().toISOString().split("T")[0];

export default function EntryDetailModal({ entry, lenderName, onClose, onPenaltyAdded }: Props) {
  const [collections, setCollections] = useState<EntryCollection[]>([]);
  const [collectionsLoading, setCollectionsLoading] = useState(true);
  const [proofDataUrl, setProofDataUrl] = useState<string | null>(null);
  const [proofLoading, setProofLoading] = useState(true);
  const [additionalTerms, setAdditionalTerms] = useState("");
  const [proofViewerBlob, setProofViewerBlob] = useState<Blob | null>(null);

  // Penalties
  const [penalties, setPenalties] = useState<EntryPenalty[]>(entry.entry_penalties ?? []);
  const [showPenaltyForm, setShowPenaltyForm] = useState(false);
  const [penaltyForm, setPenaltyForm] = useState<{ amount: string; penaltyDate: string; reason: string }>({
    amount: "",
    penaltyDate: TODAY,
    reason: "",
  });
  const [penaltySubmitting, setPenaltySubmitting] = useState(false);
  const [penaltyError, setPenaltyError] = useState<string | null>(null);

  useEffect(() => {
    const s = getAgreementSettings();
    setAdditionalTerms(s.additionalTerms);

    getEntryCollections(entry.entry_id)
      .then(setCollections)
      .catch(() => {})
      .finally(() => setCollectionsLoading(false));
    getEntryProof(entry.entry_id)
      .then((blob) => {
        if (blob) {
          const reader = new FileReader();
          reader.onload = (e) => setProofDataUrl((e.target?.result as string) ?? null);
          reader.readAsDataURL(blob);
        }
      })
      .catch(() => {})
      .finally(() => setProofLoading(false));
  }, [entry.entry_id]);

  const originalAmount = Number(entry.original_amount);
  const collected = entry.total_collected ?? 0;
  const totalManualPenalties = penalties.reduce((s, p) => s + Number(p.amount), 0);
  const stillOwed = Math.max(0, (entry.still_owed ?? originalAmount) + totalManualPenalties);
  const collectedPct = originalAmount > 0 ? Math.min(100, Math.round((collected / (originalAmount + totalManualPenalties)) * 100)) : 0;
  const isOverdue = entry.entry_status !== "Closed"
    && entry.expected_payback_date != null
    && new Date(entry.expected_payback_date) < new Date();

  const penaltyRate = entry.penalty_rate ?? 0;
  let autoPenaltyEstimate = 0;
  if (isOverdue && penaltyRate > 0) {
    const dueDate = new Date(entry.expected_payback_date!);
    const now = new Date();
    const monthsOverdue = Math.max(0, (now.getFullYear() - dueDate.getFullYear()) * 12 + (now.getMonth() - dueDate.getMonth()));
    const remainingBalance = entry.still_owed ?? originalAmount;
    autoPenaltyEstimate = remainingBalance * (penaltyRate / 100) * monthsOverdue;
  }

  const settings = getAgreementSettings();
  const effectiveLenderName = settings.lenderNameOverride.trim() || lenderName;
  const todayStr = new Date().toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" });

  const handlePrint = () => {
    const w = window.open("", "_blank");
    if (!w) return;
    const sigHtml = proofDataUrl
      ? `<img src="${proofDataUrl}" style="max-width:280px;height:72px;object-fit:contain;display:block;" />`
      : `<span class="sig-line"></span>`;
    w.document.write(buildPrintHtml({ lenderName: effectiveLenderName, entry, todayStr, sigHtml, additionalTerms }));
    w.document.close();
    setTimeout(() => w.print(), 400);
  };

  const handleViewCollectionProof = async (collectionId: string) => {
    try {
      const blob = await getCollectionProof(entry.entry_id, collectionId);
      if (!blob) return;
      setProofViewerBlob(blob);
    } catch {
      // silently ignore
    }
  };

  const handleAddPenalty = async () => {
    const amount = Number(penaltyForm.amount);
    if (!penaltyForm.amount || !Number.isFinite(amount) || amount <= 0) {
      setPenaltyError("Amount must be greater than 0");
      return;
    }
    if (!penaltyForm.penaltyDate) {
      setPenaltyError("Date is required");
      return;
    }
    setPenaltySubmitting(true);
    setPenaltyError(null);
    try {
      const payload: PenaltyRequest = {
        amount,
        penaltyDate: penaltyForm.penaltyDate,
        reason: penaltyForm.reason.trim() || undefined,
      };
      const created = await addEntryPenalty(entry.entry_id, payload);
      setPenalties((prev) => [...prev, created]);
      onPenaltyAdded?.(created);
      setPenaltyForm({ amount: "", penaltyDate: TODAY, reason: "" });
      setShowPenaltyForm(false);
    } catch (err) {
      setPenaltyError(err instanceof Error ? err.message : "Failed to add penalty");
    } finally {
      setPenaltySubmitting(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4">
      <div className="flex h-full max-h-[90vh] w-full max-w-3xl flex-col overflow-hidden rounded-2xl bg-white shadow-2xl">

        {/* Header */}
        <div className="flex items-center justify-between border-b border-slate-200 px-6 py-4">
          <div className="flex items-center gap-3">
            <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-full bg-slate-800 text-sm font-bold text-white">
              {entry.debtor_name.charAt(0).toUpperCase()}
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-base font-semibold text-slate-900">{entry.debtor_name}</h2>
                <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${STATUS_COLORS[entry.entry_status] ?? "bg-slate-100 text-slate-600"}`}>
                  {entry.entry_status}
                </span>
                {isOverdue && (
                  <span className="rounded-full bg-red-100 px-2 py-0.5 text-xs font-medium text-red-600">Overdue</span>
                )}
              </div>
              <p className="text-xs text-slate-400">ID: {entry.entry_id.slice(0, 8)}…</p>
            </div>
          </div>
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handlePrint}
              className="inline-flex items-center gap-1.5 rounded-lg border border-slate-300 px-3 py-1.5 text-sm text-slate-600 hover:bg-slate-50"
            >
              <Printer className="h-4 w-4" /> Print Agreement
            </button>
            <button type="button" onClick={onClose} className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-100">
              <X className="h-4 w-4" />
            </button>
          </div>
        </div>

        {/* Body */}
        <div className="flex-1 overflow-y-auto p-6 space-y-5">

          {/* Financial summary */}
          <div className="grid grid-cols-3 gap-3">
            <div className="rounded-xl border border-slate-200 bg-slate-50 p-4 text-center">
              <p className="text-[11px] font-medium uppercase tracking-wider text-slate-400">Loan Amount</p>
              <p className="mt-1 text-xl font-bold text-slate-900">{entry.currency} {fmtAmt(originalAmount)}</p>
            </div>
            <div className="rounded-xl border border-emerald-100 bg-emerald-50 p-4 text-center">
              <p className="text-[11px] font-medium uppercase tracking-wider text-emerald-500">Collected</p>
              <p className="mt-1 text-xl font-bold text-emerald-700">{entry.currency} {fmtAmt(collected)}</p>
            </div>
            <div className="rounded-xl border border-rose-100 bg-rose-50 p-4 text-center">
              <p className="text-[11px] font-medium uppercase tracking-wider text-rose-400">Still Owed</p>
              <p className="mt-1 text-xl font-bold text-rose-700">{entry.currency} {fmtAmt(stillOwed)}</p>
            </div>
          </div>

          <div>
            <div className="mb-1 flex justify-between text-xs text-slate-500">
              <span>Collection progress</span><span className="font-semibold">{collectedPct}%</span>
            </div>
            <div className="h-2 w-full overflow-hidden rounded-full bg-slate-200">
              <div
                className={`h-full rounded-full transition-all ${entry.entry_status === "Closed" ? "bg-emerald-500" : "bg-sky-400"}`}
                style={{ width: `${collectedPct}%` }}
              />
            </div>
          </div>

          {/* Entry details */}
          <div className="rounded-xl border border-slate-200 bg-white p-4">
            <p className="mb-3 text-[10px] font-bold uppercase tracking-wider text-slate-400">Entry Details</p>
            <dl className="grid grid-cols-2 gap-x-8 gap-y-3 text-sm">
              <div><dt className="text-[11px] text-slate-400">Lending Date</dt><dd className="font-medium text-slate-800">{fmtDate(entry.lending_date)}</dd></div>
              <div>
                <dt className="text-[11px] text-slate-400">Expected Payback</dt>
                <dd className={`font-medium ${isOverdue ? "text-red-600" : "text-slate-800"}`}>{fmtDate(entry.expected_payback_date)}</dd>
              </div>
              <div><dt className="text-[11px] text-slate-400">Lender</dt><dd className="font-medium text-slate-800">{effectiveLenderName}</dd></div>
              <div><dt className="text-[11px] text-slate-400">Debtor</dt><dd className="font-medium text-slate-800">{entry.debtor_name}</dd></div>
              <div><dt className="text-[11px] text-slate-400">Currency</dt><dd className="font-medium text-slate-800">{entry.currency}</dd></div>
              <div><dt className="text-[11px] text-slate-400">Penalty Rate</dt><dd className="font-medium text-slate-800">{penaltyRate > 0 ? `${penaltyRate}% / month` : "—"}</dd></div>
              <div><dt className="text-[11px] text-slate-400">Collections</dt><dd className="font-medium text-slate-800">{collections.length} record{collections.length !== 1 ? "s" : ""}</dd></div>
              {entry.notes && (
                <div className="col-span-2">
                  <dt className="text-[11px] text-slate-400">Notes / Purpose</dt>
                  <dd className="font-medium text-slate-800">{entry.notes}</dd>
                </div>
              )}
            </dl>
          </div>

          {/* Agreement proof — read-only */}
          <div className="rounded-xl border border-slate-200 bg-white p-4">
            <div className="mb-3 flex items-center gap-2">
              <p className="text-[10px] font-bold uppercase tracking-wider text-slate-400">Agreement Proof / Borrower Signature</p>
              <span className="inline-flex items-center gap-1 rounded-full bg-slate-100 px-2 py-0.5 text-[10px] text-slate-500">
                <Lock className="h-2.5 w-2.5" /> Read-only
              </span>
            </div>

            {proofLoading ? (
              <p className="text-xs text-slate-400 animate-pulse">Loading…</p>
            ) : proofDataUrl ? (
              <div className="overflow-hidden rounded-lg border border-slate-200 bg-slate-50">
                {proofDataUrl.startsWith("data:application/pdf") ? (
                  <div className="flex items-center gap-2 p-4 text-sm text-slate-600">
                    <FileText className="h-5 w-5 text-rose-400" /> PDF agreement document
                  </div>
                ) : (
                  <img src={proofDataUrl} alt="Borrower signature" className="max-h-48 w-full object-contain p-2" />
                )}
              </div>
            ) : (
              <p className="text-sm text-slate-400">No signature or proof recorded for this entry.</p>
            )}
          </div>

          {/* Penalties section */}
          <div className="rounded-xl border border-slate-200 bg-white p-4">
            <div className="mb-3 flex items-center justify-between">
              <p className="text-[10px] font-bold uppercase tracking-wider text-slate-400">Penalties</p>
              <button
                onClick={() => { setShowPenaltyForm((v) => !v); setPenaltyError(null); }}
                className="inline-flex items-center gap-1 rounded-lg border border-slate-300 px-2.5 py-1 text-xs font-medium text-slate-600 hover:bg-slate-50"
              >
                <Plus className="h-3 w-3" /> Add Penalty
              </button>
            </div>

            {isOverdue && penaltyRate > 0 && autoPenaltyEstimate > 0 && (
              <div className="mb-3 flex items-start gap-2 rounded-lg border border-amber-200 bg-amber-50 px-3 py-2.5 text-xs text-amber-700">
                <AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" />
                <span>
                  Auto-penalty estimate: <strong>{entry.currency} {fmtAmt(autoPenaltyEstimate)}</strong> ({penaltyRate}%/mo × overdue months).
                  Add a manual penalty below to record it officially.
                </span>
              </div>
            )}

            {penalties.length === 0 ? (
              <p className="text-sm text-slate-400">No penalties recorded.</p>
            ) : (
              <div className="mb-3 overflow-hidden rounded-lg border border-slate-100">
                <table className="w-full text-sm">
                  <thead>
                    <tr className="border-b border-slate-100 bg-slate-50 text-left text-[11px] font-medium uppercase tracking-wider text-slate-400">
                      <th className="px-3 py-2">Date</th>
                      <th className="px-3 py-2">Amount</th>
                      <th className="px-3 py-2">Reason</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-50">
                    {penalties.map((p) => (
                      <tr key={p.penalty_id}>
                        <td className="px-3 py-2 text-slate-600">{fmtDate(p.penalty_date)}</td>
                        <td className="px-3 py-2 font-semibold text-rose-600">{entry.currency} {fmtAmt(Number(p.amount))}</td>
                        <td className="px-3 py-2 text-slate-500">{p.reason || <span className="text-slate-300">—</span>}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}

            {showPenaltyForm && (
              <div className="rounded-lg border border-slate-200 bg-slate-50 p-3 space-y-2">
                {penaltyError && (
                  <p className="rounded-lg border border-red-200 bg-red-50 px-3 py-1.5 text-xs text-red-700">{penaltyError}</p>
                )}
                <div className="grid gap-2 sm:grid-cols-2">
                  <div>
                    <label className="mb-1 block text-xs font-medium text-slate-600">Amount *</label>
                    <input
                      type="number"
                      min="0.01"
                      step="0.01"
                      value={penaltyForm.amount}
                      onChange={(e) => setPenaltyForm((p) => ({ ...p, amount: e.target.value }))}
                      placeholder="0.00"
                      className="w-full rounded-lg border border-slate-300 px-3 py-1.5 text-sm focus:border-slate-500 focus:outline-none"
                    />
                  </div>
                  <div>
                    <label className="mb-1 block text-xs font-medium text-slate-600">Date *</label>
                    <input
                      type="date"
                      value={penaltyForm.penaltyDate}
                      onChange={(e) => setPenaltyForm((p) => ({ ...p, penaltyDate: e.target.value }))}
                      className="w-full rounded-lg border border-slate-300 px-3 py-1.5 text-sm focus:border-slate-500 focus:outline-none"
                    />
                  </div>
                </div>
                <input
                  type="text"
                  value={penaltyForm.reason}
                  onChange={(e) => setPenaltyForm((p) => ({ ...p, reason: e.target.value }))}
                  placeholder="Reason (optional)"
                  className="w-full rounded-lg border border-slate-300 px-3 py-1.5 text-sm focus:border-slate-500 focus:outline-none"
                />
                <div className="flex justify-end gap-2 pt-1">
                  <button
                    onClick={() => { setShowPenaltyForm(false); setPenaltyError(null); }}
                    className="rounded-lg border border-slate-300 px-3 py-1.5 text-xs font-medium text-slate-600 hover:bg-slate-50"
                  >
                    Cancel
                  </button>
                  <button
                    onClick={handleAddPenalty}
                    disabled={penaltySubmitting}
                    className="rounded-lg bg-rose-600 px-3 py-1.5 text-xs font-medium text-white hover:bg-rose-700 disabled:opacity-50"
                  >
                    {penaltySubmitting ? "Saving…" : "Save Penalty"}
                  </button>
                </div>
              </div>
            )}
          </div>

          {/* Collection history */}
          <div className="rounded-xl border border-slate-200 bg-white p-4">
            <div className="mb-3 flex items-center justify-between">
              <p className="text-[10px] font-bold uppercase tracking-wider text-slate-400">Collection History</p>
              <p className="text-xs text-slate-400">{collections.length} record{collections.length !== 1 ? "s" : ""}</p>
            </div>
            {collectionsLoading ? (
              <p className="text-xs text-slate-400 animate-pulse">Loading…</p>
            ) : collections.length === 0 ? (
              <p className="text-sm text-slate-400">No collections recorded yet.</p>
            ) : (
              <div className="overflow-hidden rounded-lg border border-slate-100">
                <table className="w-full text-sm">
                  <thead>
                    <tr className="border-b border-slate-100 bg-slate-50 text-left text-[11px] font-medium uppercase tracking-wider text-slate-400">
                      <th className="px-3 py-2">Date</th>
                      <th className="px-3 py-2">Amount</th>
                      <th className="px-3 py-2">Method</th>
                      <th className="px-3 py-2">Notes</th>
                      <th className="px-3 py-2 text-center">Proof</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-50">
                    {[...collections].sort((a, b) => a.collection_date.localeCompare(b.collection_date)).map((c) => (
                      <tr key={c.collection_id} className={c.is_archived ? "opacity-40" : ""}>
                        <td className="px-3 py-2 text-slate-600">{fmtDate(c.collection_date)}</td>
                        <td className={`px-3 py-2 font-semibold text-emerald-700 ${c.is_archived ? "line-through" : ""}`}>{entry.currency} {fmtAmt(c.amount_collected)}</td>
                        <td className="px-3 py-2">
                          <span className="rounded-full bg-slate-100 px-2 py-0.5 text-xs text-slate-600">{c.payment_method}</span>
                          {c.is_archived && <span className="ml-1 rounded-full bg-amber-100 px-1.5 py-0.5 text-[10px] font-medium text-amber-600">Archived</span>}
                        </td>
                        <td className="px-3 py-2 text-slate-500">{c.notes || <span className="text-slate-300">—</span>}</td>
                        <td className="px-3 py-2 text-center">
                          {c.proof_filename ? (
                            <button
                              onClick={() => handleViewCollectionProof(c.collection_id)}
                              className="rounded-lg p-1 text-sky-500 hover:bg-sky-50"
                              title="View proof"
                            >
                              <Paperclip className="h-3.5 w-3.5" />
                            </button>
                          ) : (
                            <span className="text-slate-300">—</span>
                          )}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </div>
      </div>

      {proofViewerBlob && (
        <ProofViewerModal blob={proofViewerBlob} onClose={() => setProofViewerBlob(null)} />
      )}
    </div>
  );
}

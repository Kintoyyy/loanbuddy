package com.example.loanbuddy

import android.os.Build
import android.os.Bundle
import android.view.*
import android.widget.Button
import android.widget.TextView
import android.widget.Toast
import androidx.annotation.RequiresApi
import androidx.fragment.app.DialogFragment
import androidx.lifecycle.lifecycleScope
import com.example.loanbuddy.api.RetrofitClient
import com.example.loanbuddy.data.Loan
import com.example.loanbuddy.ui.SignaturePadView
import kotlinx.coroutines.launch
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.MultipartBody
import okhttp3.RequestBody.Companion.toRequestBody
import java.text.NumberFormat
import java.util.Locale

class LoanAgreementDialog : DialogFragment() {

    private var loanId = ""
    private var borrowerName = ""
    private var lenderName = ""
    private var amount = 0.0
    private var dateLent = ""
    private var dueDate: String? = null

    companion object {
        fun newInstance(loan: Loan, lenderName: String) = LoanAgreementDialog().apply {
            this.loanId = loan.loan_id
            this.borrowerName = loan.borrower_name
            this.lenderName = lenderName
            this.amount = loan.amount
            this.dateLent = loan.date_lent
            this.dueDate = loan.due_date
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setStyle(DialogFragment.STYLE_NO_FRAME, R.style.Theme_LoanBuddy)
    }

    override fun onCreateView(inflater: LayoutInflater, container: ViewGroup?, saved: Bundle?): View =
        inflater.inflate(R.layout.dialog_agreement, container, false)

    override fun onStart() {
        super.onStart()
        dialog?.window?.setLayout(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT)
    }

    @RequiresApi(Build.VERSION_CODES.O)
    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        val fmt = NumberFormat.getNumberInstance(Locale("en", "PH"))
        val today = java.time.LocalDate.now().toString()

        view.findViewById<TextView>(R.id.text_lender_name).text = lenderName
        view.findViewById<TextView>(R.id.text_borrower_name).text = borrowerName
        view.findViewById<TextView>(R.id.text_agreement_intro).text =
            "This Personal Loan Agreement is entered into as of ${fmtDate(dateLent)}, " +
            "by and between the Lender and Borrower named above."
        view.findViewById<TextView>(R.id.text_section_amount).text =
            "The Lender agrees to loan the Borrower the principal sum of ₱${fmt.format(amount)}. " +
            "The Borrower hereby acknowledges receipt of this amount on ${fmtDate(dateLent)}."
        view.findViewById<TextView>(R.id.text_section_repayment).text =
            if (dueDate != null)
                "The Borrower agrees to repay the full principal amount of ₱${fmt.format(amount)} " +
                "on or before ${fmtDate(dueDate!!)}."
            else
                "The Borrower agrees to repay the full principal amount of ₱${fmt.format(amount)} " +
                "upon demand by the Lender."
        view.findViewById<TextView>(R.id.text_agreement_footer).text =
            "Generated by LoanBuddy · $today"

        val signaturePad = view.findViewById<SignaturePadView>(R.id.signature_pad)
        val btnSign = view.findViewById<Button>(R.id.btn_sign)
        val btnClear = view.findViewById<Button>(R.id.btn_clear)
        val btnSkip = view.findViewById<Button>(R.id.btn_skip)

        btnSign.isEnabled = false
        btnSign.alpha = 0.4f
        signaturePad.onChanged = { hasContent ->
            btnSign.isEnabled = hasContent
            btnSign.alpha = if (hasContent) 1f else 0.4f
        }

        view.findViewById<View>(R.id.btn_close).setOnClickListener { dismiss() }
        btnClear.setOnClickListener { signaturePad.clear() }
        btnSkip.setOnClickListener { dismiss() }
        btnSign.setOnClickListener { if (!signaturePad.isEmpty()) uploadSignature(signaturePad, btnSign) }
    }

    private fun uploadSignature(pad: SignaturePadView, btnSign: Button) {
        val token = AuthManager.getBearerToken(requireContext())
        val bytes = pad.toByteArray()
        val body = bytes.toRequestBody("image/png".toMediaType())
        val part = MultipartBody.Part.createFormData("file", "signature.png", body)

        btnSign.isEnabled = false
        btnSign.text = "Saving…"

        lifecycleScope.launch {
            try {
                RetrofitClient.apiService.uploadLoanProof(token, loanId, part)
                Toast.makeText(requireContext(), "Agreement signed & saved", Toast.LENGTH_SHORT).show()
                dismiss()
            } catch (e: Exception) {
                Toast.makeText(requireContext(), "Upload failed: ${e.message}", Toast.LENGTH_SHORT).show()
                btnSign.isEnabled = true
                btnSign.text = "Sign & Save"
            }
        }
    }

    private fun fmtDate(d: String): String {
        return try {
            val parts = d.split("-")
            val months = arrayOf("January", "February", "March", "April", "May", "June",
                "July", "August", "September", "October", "November", "December")
            "${months[parts[1].toInt() - 1]} ${parts[2].toInt()}, ${parts[0]}"
        } catch (_: Exception) { d }
    }
}
